func TestGradeTypeString(t *testing.T) {
	assignment := Assignment
	actual_assignment := assignment.String()

	if actual_assignment != "assignment" {
		t.Errorf("Expected String() of GradeType Assignment to be 'assignment', got '%s'", actual_assignment)
	}

	exam := Exam
	actual_exam := exam.String()

	if actual_exam != "exam" {
		t.Errorf("Expected String() of GradeType Exam to be 'exam', got '%s'", actual_exam)
	}

	essay := Essay
	actual_essay := essay.String()

	if actual_essay != "essay" {
		t.Errorf("Expected String() of GradeType essay to be 'essay', got '%s'", actual_essay)
	}
}

